// Helper functions
export function t(key, params = {}) {
  const keys = key.split('.');
  let value = strings;
  
  for (const k of keys) {
    value = value?.[k];
    if (!value) return key;
  }
  
  // Replace placeholders
  if (typeof value === 'string') {
    return value.replace(/\{(\w+)\}/g, (match, param) => 
      params[param] !== undefined ? params[param] : match
    );
  }
  
  return value;
}
